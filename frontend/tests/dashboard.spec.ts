import {test,expect} from '@playwright/test';
test('real local dashboard navigation, saved reports and quality evidence',async({page})=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Your local intelligence lab.'})).toBeVisible();
  await expect(page.getByText('Apple M2',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Model Library',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Installed runtime models'})).toBeVisible();
  await page.getByRole('button',{name:'Quantization Studio',exact:true}).click();
  await expect(page.getByLabel('Higher-precision GGUF source')).toBeVisible();
  await page.getByRole('button',{name:'Benchmark & Evaluation',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Saved quality evaluations'})).toBeVisible();
  await expect(page.getByLabel('Public screening suite')).toBeVisible();
  await page.getByRole('button',{name:'Comparison Reports',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Select saved experiments'})).toBeVisible();
  const boxes=page.getByRole('checkbox');
  expect(await boxes.count()).toBeGreaterThanOrEqual(2);
  await boxes.nth(0).check();await boxes.nth(1).check();
  await page.getByRole('button',{name:'Compare selected'}).click();
  await expect(page.getByRole('status')).toHaveText('Comparison loaded');
  await page.getByLabel('Minimum quality (%)').fill('70');
  await page.getByRole('button',{name:'Find a configuration'}).click();
  await expect(page.getByRole('status')).toHaveText('Recommendation checked');
  const download=page.waitForEvent('download');
  await page.getByRole('link',{name:'JSON',exact:true}).first().click();
  expect((await download).suggestedFilename()).toMatch(/experiment-.*\.json/);
  expect(errors).toEqual([]);
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Your local intelligence lab.'})).toBeVisible();
  await page.screenshot({path:'../.feather/dashboard-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('heading',{name:'Your local intelligence lab.'})).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:'../.feather/dashboard-mobile.png',fullPage:true});
});
