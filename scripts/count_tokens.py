"""Record the token length of every prompt in configs/prompt_sets/*.jsonl.

    uv run python scripts/count_tokens.py --tokenizer-label NAME --vocab PATH.gguf

Counts come from llama-tokenize at the pinned commit with default settings
(BOS added), which matched llama-server's `prompt_n` exactly in the smoke test.
Output: configs/prompt_sets/token_counts.yaml, keyed by tokenizer label, then
prompt id, with the sha256 of the prompt text, so stale counts are detected.
"""
import argparse, ast, hashlib, json, subprocess, sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
TOK = ROOT / "third_party/llama.cpp/build/bin/llama-tokenize"
OUT = ROOT / "configs/prompt_sets/token_counts.yaml"

a = argparse.ArgumentParser()
a.add_argument("--tokenizer-label", required=True)
a.add_argument("--vocab", required=True, help="GGUF with the tokenizer (vocab-only is fine)")
a = a.parse_args()
vocab = Path(a.vocab).resolve()
data = yaml.safe_load(OUT.read_text()) if OUT.exists() else {}
entry = {"vocab_file": str(vocab.relative_to(ROOT)) if vocab.is_relative_to(ROOT) else str(vocab),
         "vocab_sha256": hashlib.sha256(vocab.read_bytes()).hexdigest(),
         "llama_cpp_commit": subprocess.run(["git", "-C", str(ROOT / "third_party/llama.cpp"),
                                             "rev-parse", "HEAD"], capture_output=True,
                                            text=True).stdout.strip(),
         "bos_added": True, "prompts": {}}
for f in sorted((ROOT / "configs/prompt_sets").glob("*.jsonl")):
    for line in f.read_text().splitlines():
        if not line.strip():
            continue
        p = json.loads(line)
        r = subprocess.run([str(TOK), "-m", str(vocab), "--stdin", "--ids", "--log-disable"],
                           input=p["prompt"], capture_output=True, text=True, check=True)
        n = len(ast.literal_eval(r.stdout.strip().splitlines()[-1]))
        entry["prompts"][p["id"]] = {"set": f.stem, "tokens": n,
                                     "text_sha256": hashlib.sha256(p["prompt"].encode()).hexdigest()}
data[a.tokenizer_label] = entry
OUT.write_text("# Generated by scripts/count_tokens.py. Do not edit by hand.\n" +
               yaml.safe_dump(data, sort_keys=True))
for pid, v in entry["prompts"].items():
    print(f"{v['set']:>13} {pid:>7} {v['tokens']:>5}")
